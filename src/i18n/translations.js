export function tr(lang, key) {
  const table = TRANSLATIONS[lang] || TRANSLATIONS.en;
  return table[key] ?? TRANSLATIONS.en[key] ?? key;
}

export function getLocalizedName(item, lang) {
  if (!item) return '';
  if (typeof item.name === 'string') return item.name;
  return item.name?.[lang] || item.name?.en || item.name?.kn || '';
}

export function getSecondaryName(item, lang) {
  if (!item || typeof item.name !== 'object') return '';
  const other = lang === 'kn' ? item.name?.en : item.name?.kn;
  const primary = getLocalizedName(item, lang);
  return other && other !== primary ? other : '';
}

export function translateStatus(value, lang) {
  const dict = STATUS_TRANSLATIONS[lang] || STATUS_TRANSLATIONS.en;
  const key = String(value || '');
  return dict[key] || dict[key.toLowerCase()] || value;
}

export function translateAssetType(typeValue, lang) {
  const dict = TYPE_TRANSLATIONS[lang] || TYPE_TRANSLATIONS.en;
  return dict[typeValue] || typeValue || '—';
}

export function translateWardShort(wardStr, lang) {
  if (!wardStr) return '';
  if (lang !== 'kn') return wardStr;
  return String(wardStr).replace(/^Ward\s*/i, 'ವಾರ್ಡ್ ');
}

export function loadSavedLanguage() {
  try {
    const val = window.localStorage.getItem(LANG_STORAGE_KEY);
    return val === 'kn' ? 'kn' : 'en';
  } catch {
    return 'en';
  }
}

export function saveLanguage(lang) {
  try {
    window.localStorage.setItem(LANG_STORAGE_KEY, lang);
  } catch {
    // Ignore storage errors
  }
}
